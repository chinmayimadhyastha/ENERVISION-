/**
 * Resolves an icon by name. Accepts either a string (registry lookup) or a
 * ready React element, so callers can pass `<Radar />` directly.
 */
export function Icon({ name, className = 'h-4 w-4', strokeWidth = 2, ...rest }) {
  if (!name) return null
  if (typeof name !== 'string') return name
  const Cmp = ICONS[name] || CircleDot
  return <Cmp className={className} strokeWidth={strokeWidth} {...rest} />
}

export default Icon
